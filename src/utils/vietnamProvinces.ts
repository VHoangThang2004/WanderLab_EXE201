/**
 * Hàm chuẩn hóa chuỗi tiếng Việt: chuyển chữ thường, loại bỏ dấu tiếng Việt và ký tự đ/Đ
 */
export function normalizeSearchString(str: string): string {
  if (!str) return "";
  return str
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/đ/g, "d")
    .replace(/Đ/g, "d")
    .trim();
}
